// Installs pi-launch so it is the only `pi` on PATH:
//  1. Real Pi goes into a private npm prefix (not on PATH).
//  2. ~/.local/bin/pi and pi-launch become tiny shims pointing at that install.
//  3. Other npm Pi installations on PATH (e.g. nvm global) are uninstalled.
// Re-running is safe. Pass --keep-other-pi to skip step 3.
import { spawnSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { PACKAGE, findOtherPis, findPiRoot, findRealPi, isPiLaunch, privatePrefix, shimMarker, wrapperPath } from '../launcher.mjs';
import { ensureCompatible } from '../compatibility.mjs';

const keepOther = process.argv.includes('--keep-other-pi');
const home = homedir();
const bin = join(home, '.local/bin');
const shims = ['pi', 'pi-launch'].map(name => join(bin, name));
const prefix = privatePrefix();
const npm = existsSync(join(dirname(process.execPath), 'npm')) ? join(dirname(process.execPath), 'npm') : 'npm';

function run(args) {
  console.log(`$ npm ${args.join(' ')}`);
  const env = { ...process.env, PATH: `${dirname(process.execPath)}:${process.env.PATH ?? ''}` };
  const result = spawnSync(npm, args, { stdio: 'inherit', env });
  if (result.status !== 0) throw new Error(`npm ${args.join(' ')} failed`);
}

// Never overwrite an unrelated executable.
for (const shim of shims) {
  let exists = false;
  try { lstatSync(shim); exists = true; } catch { /* absent */ }
  if (exists && !isPiLaunch(shim)) throw new Error(`Refusing to overwrite ${shim}; it is not pi-launch.`);
}

// 1. Private Pi installation. Keep the currently installed version when there is one.
const others = findOtherPis().map(executable => {
  try { return { executable, ...findPiRoot(executable) }; } catch { return { executable }; }
});
let installation;
try {
  installation = findPiRoot(findRealPi({ override: '' }));
  console.log(`Private Pi ${installation.version} already installed at ${prefix}`);
} catch {
  const version = others.find(other => other.version)?.version ?? 'latest';
  run(['install', '-g', '--prefix', prefix, `${PACKAGE}@${version}`]);
  installation = findPiRoot(findRealPi({ override: '' }));
}
ensureCompatible(installation);

// 2. Shims pin the private Pi location; `node` comes from PATH like any npm CLI.
mkdirSync(bin, { recursive: true });
const quote = value => `'${value.replaceAll("'", "'\\''")}'`;
// `--bypass` / PI_LAUNCH_BYPASS=1 is handled here, not in JS, so it still works
// if the pi-launch checkout is broken: it runs the private Pi without the adapter.
const shim = `#!/bin/sh
${shimMarker} (generated by ${quote(join(dirname(wrapperPath), '../scripts/install-user.mjs'))})
PI_LAUNCH_PREFIX=${quote(prefix)}
export PI_LAUNCH_PREFIX
bypass="$PI_LAUNCH_BYPASS"
if [ "$1" = "--bypass" ]; then shift; bypass=1; fi
if [ -n "$bypass" ]; then exec node "$PI_LAUNCH_PREFIX/bin/pi" "$@"; fi
exec node ${quote(wrapperPath)} "$@"
`;
for (const path of shims) {
  const temporary = join(bin, `.${basename(path)}.pi-launch.tmp`);
  writeFileSync(temporary, shim, { mode: 0o755 });
  renameSync(temporary, path);
}

// 3. Remove other Pi installations that could shadow the wrapper.
const leftovers = [];
for (const other of others) {
  const match = other.root?.match(/^(.*)\/lib\/node_modules\/@earendil-works\/pi-coding-agent$/);
  if (keepOther || !match) { leftovers.push(other.executable); continue; }
  run(['uninstall', '-g', '--prefix', match[1], PACKAGE]);
}

// PATH block so shells find ~/.local/bin (most systems already include it).
const marker = '# >>> pi-launch >>>';
const block = `\n${marker}\nexport PATH="$HOME/.local/bin:$PATH"\n# <<< pi-launch <<<\n`;
for (const path of new Set(['.zshrc', '.bashrc', '.profile'].map(name => join(home, name)).concat(join(process.env.ZDOTDIR || home, '.zshrc')))) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current.includes(marker)) continue;
  if (existsSync(path) && !existsSync(`${path}.before-pi-launch`)) writeFileSync(`${path}.before-pi-launch`, current);
  writeFileSync(path, current + block);
}

console.log(`\nInstalled pi-launch:
  real Pi ${installation.version}: ${installation.root}
  shims:  ${shims.join(', ')}`);
for (const leftover of leftovers) console.log(`  warning: another Pi remains on PATH and may bypass pi-launch: ${leftover}`);
console.log('Run `hash -r` (bash) or `rehash` (zsh) in open shells.');
