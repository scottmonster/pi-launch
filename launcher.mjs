import { accessSync, constants, readFileSync, realpathSync } from 'node:fs';
import { homedir } from 'node:os';
import { delimiter, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACKAGE = '@earendil-works/pi-coding-agent';
export const repoRoot = fileURLToPath(new URL('.', import.meta.url));
export const wrapperPath = fileURLToPath(new URL('./bin/pi.mjs', import.meta.url));
export const shimMarker = '# pi-launch shim';
const wrapperMarker = '// pi-launch wrapper';

// The real Pi lives in a private Bun global directory (BUN_INSTALL) that is never
// on PATH, so the wrapper is the only `pi` any program can find. `pi update`
// runs with BUN_INSTALL pointed here, so Pi updates itself in place.
export function privatePrefix() {
  return process.env.PI_LAUNCH_PREFIX || join(process.env.XDG_DATA_HOME || join(homedir(), '.local/share'), 'pi-launch/pi');
}

export function privateRoot(prefix = privatePrefix()) {
  return join(prefix, 'install/global/node_modules', PACKAGE);
}

// Bun drops the first `--` after the script path, so always supply one.
export function scriptArgs(script, ...args) {
  return process.versions.bun ? [script, '--', ...args] : [script, ...args];
}

const quote = value => `'${value.replaceAll("'", "'\\''")}'`;

// ~/.local/bin/pi and pi-launch. Management commands and --bypass are handled
// here in sh, so they keep working even if the pi-launch JavaScript is broken.
export function shimScript({ prefix, src, bun = process.execPath }) {
  return `#!/bin/sh
${shimMarker} (generated by ${quote(join(src, 'scripts/install-user.mjs'))})
PI_LAUNCH_PREFIX=${quote(prefix)}
PI_LAUNCH_SRC=${quote(src)}
export PI_LAUNCH_PREFIX
# Bun from PATH; Bun's install location as a fallback for programs with a minimal PATH.
bun=$(command -v bun 2>/dev/null) || bun=${quote(bun)}

manage() { PI_LAUNCH_DIR="$PI_LAUNCH_SRC" exec sh "$PI_LAUNCH_SRC/install.sh" "$@"; }
usage() { echo "usage: pi launch update | pi launch uninstall|remove [--no-restore] [--keep-comments]"; }
if [ "\${0##*/}" = pi-launch ]; then
  case "\${1:-}" in
    --update) shift; manage "$@" ;;
    --uninstall|--remove) shift; manage --uninstall "$@" ;;
  esac
fi
if [ "\${1:-}" = launch ]; then
  case "\${2:-}" in
    update) shift 2; manage "$@" ;;
    uninstall|remove) shift 2; manage --uninstall "$@" ;;
    ""|help|--help|-h) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
fi

# Bypass: run the private Pi without pi-launch (pi --bypass ..., or PI_LAUNCH_BYPASS=1).
bypass="\${PI_LAUNCH_BYPASS:-}"
if [ "\${1:-}" = --bypass ]; then shift; bypass=1; fi
if [ -n "$bypass" ]; then
  if [ "\${1:-}" = update ]; then BUN_INSTALL="$PI_LAUNCH_PREFIX"; export BUN_INSTALL; fi
  exec "$bun" "$PI_LAUNCH_PREFIX/install/global/node_modules/${PACKAGE}/dist/bun/cli.js" -- "$@"
fi
exec "$bun" ${quote(join(src, 'bin/pi.mjs'))} -- "$@"
`;
}

export function isPiLaunch(path) {
  try {
    const real = realpathSync(path);
    if (real === realpathSync(wrapperPath)) return true;
    const head = readFileSync(real, 'utf8').slice(0, 200);
    return head.includes(shimMarker) || head.includes(wrapperMarker);
  } catch {
    return false;
  }
}

export function findRealPi({ override = process.env.PI_LAUNCH_REAL_PI, prefix = privatePrefix() } = {}) {
  const candidate = override ? resolve(override) : join(prefix, 'bin/pi');
  if (isPiLaunch(candidate)) throw new Error(`${candidate} points to pi-launch itself`);
  try {
    accessSync(candidate, constants.X_OK);
    return realpathSync(candidate);
  } catch (error) {
    if (override) throw new Error(`Invalid PI_LAUNCH_REAL_PI: ${error.message}`);
    throw new Error(`Pi is not installed at ${prefix}. Re-run the pi-launch install command (or \`bun run install-user\` in ${repoRoot}).`);
  }
}

// Other npm Pi installations on PATH can shadow the wrapper for programs whose
// PATH puts them first. Returns their executables so callers can warn/remove them.
export function findOtherPis(path = process.env.PATH ?? '') {
  const found = new Set();
  for (const dir of path.split(delimiter)) {
    const candidate = join(dir || '.', 'pi');
    try {
      accessSync(candidate, constants.X_OK);
      if (!isPiLaunch(candidate)) found.add(realpathSync(candidate));
    } catch { /* not present */ }
  }
  return [...found];
}

export function findPiRoot(executable) {
  let root = dirname(executable);
  while (true) {
    try {
      const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
      if (pkg.name === PACKAGE) return { root, version: pkg.version };
    } catch (error) {
      if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') throw error;
    }
    const parent = dirname(root);
    if (parent === root) break;
    root = parent;
  }
  throw new Error(`Cannot locate the Pi npm package for ${executable}. Standalone binaries and shell shims are unsupported; set PI_LAUNCH_REAL_PI to the npm Pi executable.`);
}

// Pi's Bun entry point sets up Bun-specific OAuth, Bedrock and QuickJS support
// before loading the same unbundled CLI (whose settings module the adapter patches).
export function cliEntry() {
  return process.versions.bun ? 'dist/bun/cli.js' : 'dist/cli.js';
}

export function assertCompatible({ root, version }) {
  for (const relative of [cliEntry(), 'dist/core/settings-manager.js']) {
    try { accessSync(join(root, relative), constants.R_OK); }
    catch { throw new Error(`Pi ${version} is missing ${relative}; an unbundled npm installation is required.`); }
  }
}
